// Generates the environment variable reference from the lib/env.ts schema (what is checked at start, and which
// values are accepted) and the descriptions in docs/CONFIGURATION.md (one source for the wording).
import { readFileSync } from "node:fs";
import { join } from "node:path";

/** Plain words for the schema's checks; the first that matches wins. */
const KINDS = [
  [/z\.enum\(\[([^\]]+)\]\)/, (match) => match[1].split(",").map((value) => `\`${value.trim().replace(/"/g, "")}\``).join(", ")],
  [/^\s*secret\b/, () => "32 or more characters"],
  [/^\s*serverActionsKey\b/, () => "base64 of a 16, 24 or 32-byte key"],
  [/^\s*mfaEncryptionKey\b/, () => "base64 of a 32-byte key"],
  [/regex\(\/\^\[a-f0-9\]\{64\}\$\//, () => "64 hexadecimal characters"],
  [/\.url\(/, () => "a URL"],
  [/\.email\(/, () => "an email address"],
  [/\.datetime\(/, () => "a date and time (ISO 8601)"],
  [/coerce\.number\(\)\.int\(\)(?:\.min\((\d+)\))?(?:\.positive\(\))?\.max\((\d+)\)/, (match) => `a whole number${match[1] ? ` from ${match[1]}` : ""} up to ${match[2]}`],
  [/regex\(\/\^\[1-9\]/, () => "a positive whole number"],
  [/regex\(/, () => "a fixed pattern (see lib/env.ts)"],
  [/z\.string\(\)/, () => "text"],
];

/** Every key of envSchema with what it accepts, and the ones a production start insists on. */
export function collectSchema(root) {
  const source = readFileSync(join(root, "lib", "env.ts"), "utf8");
  const block = /const envSchema = z\.object\(\{([\s\S]*?)\n\}\);/.exec(source)?.[1];
  const required = /const missing = \[([^\]]+)\]/.exec(source)?.[1];
  if (!block || !required) throw new Error("build-docs: lib/env.ts changed shape; update scripts/docs/env.mjs");
  const production = new Set([...required.matchAll(/"([A-Z0-9_]+)"/g)].map((match) => match[1]));
  return [...block.matchAll(/^ {2}([A-Z][A-Z0-9_]+): (.+)$/gm)].map(([, name, rule]) => {
    const kind = KINDS.map(([pattern, label]) => { const match = pattern.exec(rule); return match ? label(match) : null; }).find(Boolean);
    return { name, accepts: kind ?? "text", production: production.has(name), optional: /\.optional\(\)/.test(rule) };
  });
}

/** Rows of every table in docs/CONFIGURATION.md: each variable named in the first cell, with its section and text. */
export function collectDescriptions(root) {
  const lines = readFileSync(join(root, "docs", "CONFIGURATION.md"), "utf8").replace(/\r\n/g, "\n").split("\n");
  const found = new Map();
  let section = "";
  for (const line of lines) {
    const heading = /^#{2,3}\s+(.+)$/.exec(line);
    if (heading) { section = heading[1].trim(); continue; }
    if (!line.startsWith("| `")) continue;
    const cells = line.slice(1, -1).split(" | ").map((cell) => cell.trim());
    const names = [...cells[0].matchAll(/`([A-Z][A-Z0-9_]+)`/g)].map((match) => match[1]);
    const text = cells[cells.length - 1].replace(/\]\((?!https?:|#|\/)([^)]+)\)/g, "](../$1)");
    const extra = cells.length > 2 ? cells.slice(1, -1).join(", ") : "";
    for (const name of names) if (!found.has(name)) found.set(name, { section, text, extra });
  }
  return found;
}

const cell = (text) => text.replace(/\|/g, "\\|");

export function renderEnvPage(root) {
  const schema = collectSchema(root);
  const described = collectDescriptions(root);
  const inSchema = new Set(schema.map((entry) => entry.name));
  const lines = [
    "# Environment variables",
    "",
    `Every setting the app reads from its environment: ${schema.length} are checked when a production server starts, and the rest are described by where they are used.`,
    "",
    "> **Note:** This page is generated by `scripts/build-docs.mjs` from the schema in `lib/env.ts` and the wording in [Configuration](../CONFIGURATION.md). To change a description, edit `docs/CONFIGURATION.md`. Every new variable also goes into `.env.example`, `.env.production.example` and the Compose `x-app-env` blocks.",
    "",
    "## Checked at start",
    "",
    "A production server refuses to start when one of these is malformed, or when one marked as needed in production is empty.",
    "",
    "| Variable | Needed in production | Accepts | Description |",
    "|---|---|---|---|",
  ];
  for (const entry of schema) {
    const text = described.get(entry.name)?.text ?? "Not described in the configuration reference yet.";
    const needed = entry.production ? "Yes" : entry.optional ? "No" : "Always";
    lines.push(`| \`${entry.name}\` | ${needed} | ${cell(entry.accepts)} | ${text} |`);
  }
  const bySection = new Map();
  for (const [name, entry] of described) {
    if (inSchema.has(name)) continue;
    bySection.set(entry.section, [...(bySection.get(entry.section) ?? []), { name, ...entry }]);
  }
  lines.push("", "## Other settings", "", "Read where they are used rather than checked at start: by the website, the installer, the Compose files or the scripts.");
  for (const [section, rows] of bySection) {
    lines.push("", `### ${section}`, "", "| Variable | Default or where | Description |", "|---|---|---|");
    for (const row of rows) lines.push(`| \`${row.name}\` | ${row.extra || "—"} | ${row.text} |`);
  }
  lines.push("", "## Related", "", "- [Configuration](../CONFIGURATION.md)", "- [Choose your hosting](../guides/hosting/choose-your-hosting.md)", "- [Limits](limits.md)");
  return lines.join("\n");
}
