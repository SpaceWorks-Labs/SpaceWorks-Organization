// The search palette's index: titles, summaries, h2/h3 headings and a few words of each section, as a small static
// module the browser loads only when the palette opens (no filesystem at runtime, so it works in split hosting).
import { sectionExcerpts } from "./markdown.mjs";

export function buildSearchIndex(docs, sections) {
  const sectionTitle = new Map(sections.map((section) => [section.key, section.title]));
  return docs.map((doc) => ({
    slug: doc.slug,
    title: doc.title,
    section: sectionTitle.get(doc.section) ?? doc.section,
    summary: doc.summary,
    headings: sectionExcerpts(doc.body).map((heading) => [heading.id, heading.title, heading.text]),
  }));
}

export function renderSearchModule(index) {
  return [
    "// Generated by scripts/build-docs.mjs: the docs search index. Generated: do not edit.",
    "/** One doc: slug, title, section title, summary, and [id, heading, first words] for each h2 and h3. */",
    "export type SearchDoc = { slug: string; title: string; section: string; summary: string; headings: readonly (readonly [string, string, string])[] };",
    "",
    "export const SEARCH_INDEX: readonly SearchDoc[] = [",
    ...index.map((entry) => `  ${JSON.stringify(entry)},`),
    "];",
    "",
  ].join("\n");
}
